def A(key,name,groups,structure,conditions,production):
    assert set(groups)<=gids
    records.append(dict(candidate_id=key,layer='A 지문 전개',name=name,groups=groups,A=structure,E=conditions,F=production,
        count=dict(unique_passages=len(groups),unique_questions=0,actual_solution_uses=0,passage_structure_only=len(groups),
            by_exam={f:sum(groupmanifest[g]['exam_family']==f for g in groups) for f in ['KICE','LEET','MEET']}),
        evidence=[dict(unique_group=g,source='group_extractions.jsonl',field='A',links=groupmanifest[g]['source_paths']) for g in groups],
        status='현재 직접 읽은 그룹의 지문 배치 공통. 실제 풀이 사용 빈도와 별도.' ))

def B(key,name,ids,operation,conditions,production):
    assert set(ids)<=set(events)
    chosen=[events[x] for x in ids]
    records.append(dict(candidate_id=key,layer='B 발문·선지',name=name,event_ids=ids,B=operation,E=conditions,F=production,
        count=dict(unique_passages=len({s['unique_group'] for s in chosen}),unique_questions=len({s['unique_question'] for s in chosen}),
            actual_solution_uses=len(chosen),passage_structure_only=0,
            by_exam={f:dict(passages=len({s['unique_group'] for s in chosen if s['exam_family']==f}),questions=len({s['unique_question'] for s in chosen if s['exam_family']==f})) for f in ['KICE','LEET','MEET']}),
        evidence=[dict(event_id=s['event_id'],B=s['B'],C=s['C'],link='evidence_links.jsonl') for s in chosen],status='복수 실제 선지의 잠정 변형 원리'))

